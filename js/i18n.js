let _lang = localStorage.getItem('tp_lang') || 'fr';

export function getLang() { return _lang; }

export function setLang(lang) {
  if (!LANGS[lang]) return;
  _lang = lang;
  localStorage.setItem('tp_lang', lang);
}

export function t(key, vars = {}) {
  let str = LANGS[_lang][key] ?? LANGS['fr'][key] ?? key;
  Object.entries(vars).forEach(([k, v]) => { str = str.replace(`{${k}}`, v); });
  return str;
}

export function getQs() {
  return LANGS[_lang].qs;
}

export function getCat() {
  return {
    Confiance:      t('cat.confiance'),
    Conflit:        t('cat.conflit'),
    Engagement:     t('cat.engagement'),
    Responsabilite: t('cat.responsabilite'),
    Resultats:      t('cat.resultats'),
  };
}
